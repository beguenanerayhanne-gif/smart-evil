export type TranslationKey = keyof typeof translations.fr

export function getTranslatedCategoryName(
  cat: { slug: string; name: string },
  lang: Language
): string {
  const key = `cat.${cat.slug}` as keyof typeof translations.fr
  const dict = translations[lang] || translations.fr
  if (key in dict) {
    return dict[key]
  }
  return cat.name
}
